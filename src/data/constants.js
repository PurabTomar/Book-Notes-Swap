export const FALLBACK_IMAGE = "/images/book-generic.svg";

/* Legacy flat covers that earlier seed rows stored on photo_url. They were
   shared across many headings (operating-systems, programming, …), so a card
   showing one does NOT relate to its own subject heading/topic. ListingCard
   treats these as "no topic cover" and falls through to the topic-accurate
   subject cover instead. */
export const LEGACY_GENERIC_COVERS = new Set([
  "/images/operating-systems.svg",
  "/images/data-structures.svg",
  "/images/programming.svg",
  "/images/engineering-physics.svg",
  "/images/engineering-math.svg",
  "/images/engineering-graphics.svg",
  "/images/basic-electrical.svg",
  "/images/digital-logic.svg",
  "/images/computer-networks.svg",
  "/images/book-generic.svg",
  "/images/previous-year-papers.svg",
  "/images/lab-manual.svg",
  "/images/handwritten-notes.svg",
]);

export const subjectImage = (subject) => SUBJECT_IMAGES[subject] ?? FALLBACK_IMAGE;

/* Topic-accurate cover resolver used by cards/details. If a listing carries a
   legacy generic cover as its photo_url, we ignore it and resolve the cover
   that relates to the subject heading/topic. */
export const resolveCover = (subject, photoUrl) => {
  if (photoUrl && !LEGACY_GENERIC_COVERS.has(photoUrl)) return photoUrl;
  return subjectImage(subject);
};